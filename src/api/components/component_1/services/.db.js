import dotenv from 'dotenv';
import path from 'path';
import { fileURLToPath } from 'url';
const __dirname = path.dirname(fileURLToPath(import.meta.url));
dotenv.config({ path: path.resolve(__dirname, '../.env') });

//database connector
import pg from 'pg';
const { Pool } = pg;
const pool = new Pool({
  user: process.env.DB_USER,
  host: process.env.DB_HOST,
  database: process.env.DB_NAME,
  password: process.env.DB_PASSWORD,
  port: Number(process.env.DB_PORT),
});

const testConnection = async () => {
    try {
        const client = await pool.connect();
        console.log('Successfully connected to the database!');
        client.release();
    } catch (error) { 
        console.error('Database connection failed:', error);
        process.exit(1); 
    }
};


testConnection();
export default pool;

//init tables
const createTablesQuery = `
    CREATE TABLE IF NOT EXISTS Departments (
        DepartmentID INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        DepartmentName VARCHAR(100) NOT NULL
    );

    CREATE TABLE IF NOT EXISTS Users (
        EmployeeID INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        FirstName VARCHAR(50),
        LastName VARCHAR(50),
        DateOfBirth DATE,
        Gender VARCHAR(10) CHECK (Gender IN ('Male', 'Female')),
        DepartmentID INT,
        Salary DECIMAL(10, 2),
        HireDate DATE,
        UserToken INT DEFAULT floor(random() * 90000 + 10000),
        FOREIGN KEY (DepartmentID) REFERENCES Departments(DepartmentID) ON DELETE CASCADE ON UPDATE CASCADE
    );

    CREATE TABLE IF NOT EXISTS Texts (
        TextID INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        UserID INT NOT NULL,
        txtText TEXT NOT NULL,
        Timestamp TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
        FOREIGN KEY (UserID) REFERENCES Users(EmployeeID) ON DELETE CASCADE ON UPDATE CASCADE
    );

    CREATE TABLE IF NOT EXISTS Requests (
        RequestID INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        UserID INT NOT NULL,
        reqText TEXT NOT NULL,
        Timestamp TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
        FOREIGN KEY (UserID) REFERENCES Users(EmployeeID) ON DELETE CASCADE ON UPDATE CASCADE
    );
`;

const initDb = async () => {
    try {
        await pool.query(createTablesQuery);
        console.log('Tables created successfully!');
    } catch (err) {
        console.error('Error creating tables:', err);
    } finally {
        pool.end();
    }
};

initDb();



