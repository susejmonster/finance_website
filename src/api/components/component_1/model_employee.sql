-- CREATE TABLE DEFINITIONS
DROP TABLE IF EXISTS Transactions, TransactionCategories, Requests, Texts, Users, Departments CASCADE;
CREATE TABLE IF NOT EXISTS Departments (
    DepartmentID INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    DepartmentName VARCHAR(100) NOT NULL
);

CREATE TABLE IF NOT EXISTS Users (
    EmployeeID INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    FirstName VARCHAR(50),
    LastName VARCHAR(50),
    DateOfBirth DATE,
    Gender VARCHAR(10) CHECK (Gender IN ('Male', 'Female')),
    DepartmentID INT,
    Salary DECIMAL(10, 2),
    HireDate DATE,
    Pass VARCHAR(50),
    UserToken INT DEFAULT floor(random() * 90000 + 10000),
    FOREIGN KEY (DepartmentID) REFERENCES Departments(DepartmentID)
        ON DELETE CASCADE
        ON UPDATE CASCADE
);

CREATE TABLE IF NOT EXISTS Texts (
    TextID INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    UserID INT NOT NULL,
    txtText TEXT NOT NULL,
    Timestamp TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    FOREIGN KEY (UserID) REFERENCES Users(EmployeeID)
        ON DELETE CASCADE
        ON UPDATE CASCADE
);

CREATE TABLE IF NOT EXISTS Requests (
    RequestID INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    UserID INT NOT NULL,
    reqText TEXT NOT NULL,
    Timestamp TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    FOREIGN KEY (UserID) REFERENCES Users(EmployeeID)
        ON DELETE CASCADE
        ON UPDATE CASCADE
);

-- NEW: Transaction Categories
CREATE TABLE IF NOT EXISTS TransactionCategories (
    CategoryID INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    CategoryName VARCHAR(100) NOT NULL,
    CategoryType VARCHAR(50) CHECK (CategoryType IN ('Income', 'Expense')) NOT NULL
);

-- NEW: Transactions (Linked to Users and Categories)
CREATE TABLE IF NOT EXISTS Transactions (
    TransactionID INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    EmployeeID INT NOT NULL,
    CategoryID INT,
    Amount DECIMAL(12, 2) NOT NULL,
    TransactionDate DATE NOT NULL DEFAULT CURRENT_DATE,
    Description TEXT,
    FOREIGN KEY (EmployeeID) REFERENCES Users(EmployeeID)
        ON DELETE CASCADE
        ON UPDATE CASCADE,
    FOREIGN KEY (CategoryID) REFERENCES TransactionCategories(CategoryID)
        ON DELETE SET NULL
        ON UPDATE CASCADE
);


